#!/usr/bin/env bash
# Update the checkout from GitHub (git pull). Building is done by deploy/build.sh.
set -euo pipefail

usage() {
    cat <<'EOF'
Usage: server/deploy/update.sh [--help]

Updates the checkout from GitHub: git pull of the current branch (fast-forward only).
If that fails, or tracked files have local changes, it offers to reset the checkout to an
exact copy of the GitHub branch: local changes and untracked files are discarded, ignored
data (projects/, .build/) is kept. server/Package.resolved is generated: a local change to
it is discarded without asking.

On Linux, run as root: if the checkout belongs to another user (on the server: thinknodes),
it runs as that user (runuser), so no root-owned file gets into .git.

Used by deploy/daemon.sh and run.sh --update.

Options:
  --help      Show this help.
EOF
}

script="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
cd "$(dirname "$0")/.."
original_args=("$@")
while (($#)); do
    case "$1" in
        -h|--help) usage; exit 0 ;;
        *) printf 'Unknown option: %s (see --help)\n' "$1" >&2; exit 1 ;;
    esac
    shift
done

source deploy/as-owner.sh
run_as_checkout_owner "$script" ${original_args[@]+"${original_args[@]}"}

git rev-parse --git-dir >/dev/null 2>&1 || { printf 'Not a git checkout: %s\n' "$PWD" >&2; exit 1; }

reset_to_remote() {
    local branch="$1"
    printf '\nThe checkout differs from origin/%s:\n' "$branch"
    git status --short | sed 's/^/  /'
    git log --oneline FETCH_HEAD..HEAD 2>/dev/null | sed 's/^/  local commit: /'
    if [[ ! -t 0 ]]; then
        printf 'Not interactive: run it in a terminal to reset.\n' >&2
        exit 1
    fi
    read -r -p "Discard all of the above and make an exact copy of origin/$branch? [y/N] " answer
    if [[ "$answer" != [yY]* ]]; then
        printf 'Stopped. The checkout is unchanged.\n' >&2
        exit 1
    fi
    git reset --hard FETCH_HEAD
    git clean -fd -- "$(git rev-parse --show-toplevel)"
}

branch="$(git symbolic-ref --quiet --short HEAD)" || { printf 'No active git branch.\n' >&2; exit 1; }
# Package.resolved is regenerated by the package resolution of build.sh (other Swift versions add pins): not a real change.
git diff --quiet -- Package.resolved || git checkout -- Package.resolved
printf 'Updating from origin/%s...\n' "$branch"
GIT_TERMINAL_PROMPT=0 git fetch --no-tags origin "refs/heads/$branch"
# Csak a követett fájlok helyi változása akadály; a nem követett (pl. a régi mappaszerkezet maradványa) csak akkor, ha
# a frissítés felülírná – akkor a fast-forward úgyis elbukik, és jön a visszaállítás.
if [[ -n "$(git status --porcelain --untracked-files=no)" ]] || ! git merge --ff-only --quiet FETCH_HEAD; then
    reset_to_remote "$branch"
fi
printf 'Checkout: %s\n' "$(git log --oneline -1)"
