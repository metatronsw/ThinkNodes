"""Generate the static ThinkNodes help page from the hotkey table."""

import argparse
from html import escape
import json
from pathlib import Path
import re
from xml.etree import ElementTree


ROOT = Path(__file__).resolve().parents[1]


def load_groups():
    groups = json.loads((ROOT / "docs/hotkeys.json").read_text(encoding="utf-8"))
    svg = ElementTree.parse(ROOT / "Public/icons.svg")
    icons = {symbol.get("id") for symbol in svg.findall("{*}symbol")}
    seen = set()
    for group in groups:
        slug = group["id"]
        if slug in seen or slug == "peldak" or not re.fullmatch(r"[a-z][a-z0-9-]+", slug):
            raise ValueError(f"Invalid or repeated section ID: {slug}")
        seen.add(slug)
        for row in group["rows"]:
            if "icon" in row and row["icon"] not in icons:
                raise ValueError(f"Unknown icon: {row['icon']}")
            if not row["keys"] or any(not combination or not all(combination) for combination in row["keys"]):
                raise ValueError(f"Empty shortcut: {row['action']}")
    return groups


def table_row(row):
    icon = ""
    if name := row.get("icon"):
        icon = f'<svg class="ui-icon" aria-hidden="true"><use href="/icons.svg#{escape(name)}"/></svg>'
    return (
        f'<tr role="row"><th scope="row" role="rowheader">{icon}{escape(row["action"])}</th>'
        f'<td>{shortcuts(row)}</td><td>{escape(row["where"])}</td><td>{escape(row["detail"])}</td></tr>'
    )


def shortcuts(row):
    return " / ".join(
        '<span class="guide-key-group">' + " + ".join(f"<kbd>{escape(key)}</kbd>" for key in combination) + "</span>"
        for combination in row["keys"]
    )


def table(group):
    slug = group["id"]
    title = escape(group["title"])
    rows = "\n".join("          " + table_row(row) for row in group["rows"])
    return f'''<section id="{slug}" aria-labelledby="{slug}-title">
      <h2 id="{slug}-title">{title}</h2>
      <table class="guide-table panel" role="table" aria-labelledby="{slug}-title">
        <thead role="rowgroup"><tr role="row"><th scope="col">Művelet</th><th scope="col">Billentyű vagy gesztus</th><th scope="col">Hol</th><th scope="col">Mi történik</th></tr></thead>
        <tbody role="rowgroup">
{rows}
        </tbody>
      </table>
    </section>'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Exit with an error if the generated page is stale.")
    args = parser.parse_args()
    groups = load_groups()
    template = (ROOT / "docs/guide.template.html").read_text(encoding="utf-8")
    examples = {}
    for group in groups:
        for row in group["rows"]:
            if slug := row.get("id"):
                if slug in examples:
                    raise ValueError(f"Repeated shortcut ID: {slug}")
                examples[slug] = row
    template = re.sub(r"<!-- KEYS:([a-z-]+) -->", lambda match: shortcuts(examples[match[1]]), template)
    navigation = "\n      ".join(f'<a href="#{group["id"]}">{escape(group["title"])}</a>' for group in groups)
    tables = "\n\n    ".join(table(group) for group in groups)
    html = template.replace("<!-- GUIDE_NAV -->", navigation).replace("<!-- GUIDE_TABLES -->", tables)
    html = html.replace("<!doctype html>\n", "<!doctype html>\n<!-- Generated by tools/generate-guide.py from docs/hotkeys.json and docs/guide.template.html. -->\n")
    output = ROOT / "Public/utmutato.html"
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != html:
            parser.exit(1, "Public/utmutato.html is stale. Run python3 tools/generate-guide.py.\n")
    else:
        output.write_text(html, encoding="utf-8")


if __name__ == "__main__":
    main()
